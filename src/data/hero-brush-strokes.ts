export function buildHeroBrushMaskDataUri(paths: readonly string[]): string {
  const pathMarkup = paths
    .map(path => `<path d="${path}" fill="white"/>`)
    .join("");
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${HERO_BRUSH_VIEWBOX}" preserveAspectRatio="none">${pathMarkup}</svg>`;
  return `url("data:image/svg+xml,${encodeURIComponent(svg)}")`;
}

